//! Prüft, dass `Cargo.lock` nur Crates aus diesem Workspace enthält.
//!
//! Jedes Paket mit einem `source`-Eintrag stammt von außerhalb (crates.io, Git
//! oder eine andere Registry) und verstößt gegen den Grundsatz, alles selbst zu
//! bauen. Siehe `docs/architektur.md`, Abschnitt 1.1.
//!
//! Aufruf: `cargo run -p deps-guard [-- <Pfad zu Cargo.lock>]`

#![forbid(unsafe_code)]

use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// Ein Eintrag aus `Cargo.lock`, der von außerhalb des Workspace stammt.
#[derive(Debug, PartialEq, Eq)]
struct External {
    name: String,
    source: String,
}

/// Ergebnis der Prüfung einer `Cargo.lock`.
#[derive(Debug, PartialEq, Eq)]
struct Report {
    entries: usize,
    external: Vec<External>,
}

#[derive(Default)]
struct Entry {
    name: Option<String>,
    source: Option<String>,
}

/// Liest `Cargo.lock` zeilenweise. Geprüft werden `[[package]]` und
/// `[[patch.unused]]`, denn beide können eine externe Quelle haben.
fn check(lock: &str) -> Report {
    let mut report = Report {
        entries: 0,
        external: Vec::new(),
    };
    let mut entry: Option<Entry> = None;
    for line in lock.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            finish(entry.take(), &mut report);
            if line == "[[package]]" || line == "[[patch.unused]]" {
                entry = Some(Entry::default());
            }
            continue;
        }
        let Some(current) = entry.as_mut() else {
            continue;
        };
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let value = unquote(value.trim()).to_owned();
        match key.trim() {
            "name" => current.name = Some(value),
            "source" => current.source = Some(value),
            _ => {}
        }
    }
    finish(entry, &mut report);
    report
}

fn finish(entry: Option<Entry>, report: &mut Report) {
    let Some(entry) = entry else {
        return;
    };
    report.entries += 1;
    if let Some(source) = entry.source {
        report.external.push(External {
            name: entry.name.unwrap_or_else(|| "<ohne Namen>".to_owned()),
            source,
        });
    }
}

fn unquote(value: &str) -> &str {
    value
        .strip_prefix('"')
        .and_then(|inner| inner.strip_suffix('"'))
        .unwrap_or(value)
}

fn main() -> ExitCode {
    let path = std::env::args_os().nth(1).map_or_else(
        || {
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("..")
                .join("..")
                .join("Cargo.lock")
        },
        PathBuf::from,
    );
    let lock = match std::fs::read_to_string(&path) {
        Ok(lock) => lock,
        Err(err) => {
            eprintln!(
                "deps-guard: {} lässt sich nicht lesen: {err}",
                path.display()
            );
            return ExitCode::FAILURE;
        }
    };
    let report = check(&lock);
    if report.entries == 0 {
        eprintln!(
            "deps-guard: {} enthält keine Pakete. Ist das die richtige Datei?",
            path.display()
        );
        return ExitCode::FAILURE;
    }
    if report.external.is_empty() {
        println!(
            "deps-guard: {} Pakete geprüft, keine externen Abhängigkeiten.",
            report.entries
        );
        return ExitCode::SUCCESS;
    }
    eprintln!(
        "deps-guard: {} externe Abhängigkeiten gefunden. Erlaubt sind nur Crates aus diesem Workspace (docs/architektur.md, Abschnitt 1.1):",
        report.external.len()
    );
    for external in &report.external {
        eprintln!("  {} ({})", external.name, external.source);
    }
    ExitCode::FAILURE
}

#[cfg(test)]
mod tests {
    use super::*;

    const WORKSPACE_ONLY: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "mb-base"
version = "0.0.0"

[[package]]
name = "meinbrowser"
version = "0.0.0"
dependencies = [
 "mb-base",
]
"#;

    const FROM_REGISTRY: &str = r#"
[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0000"
"#;

    const FROM_GIT: &str = r#"
[[package]]
name = "foo"
version = "0.1.0"
source = "git+https://example.com/foo.git#0123456"
"#;

    const UNUSED_PATCH: &str = r#"
[[patch.unused]]
name = "bar"
version = "0.2.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

    fn external(name: &str, source: &str) -> External {
        External {
            name: name.to_owned(),
            source: source.to_owned(),
        }
    }

    #[test]
    fn workspace_crates_are_allowed() {
        assert_eq!(
            check(WORKSPACE_ONLY),
            Report {
                entries: 2,
                external: Vec::new(),
            }
        );
    }

    #[test]
    fn registry_and_git_sources_are_reported() {
        let lock = format!("{WORKSPACE_ONLY}{FROM_REGISTRY}{FROM_GIT}");
        assert_eq!(
            check(&lock),
            Report {
                entries: 4,
                external: vec![
                    external(
                        "serde",
                        "registry+https://github.com/rust-lang/crates.io-index"
                    ),
                    external("foo", "git+https://example.com/foo.git#0123456"),
                ],
            }
        );
    }

    #[test]
    fn unused_patches_are_reported() {
        let lock = format!("{WORKSPACE_ONLY}{UNUSED_PATCH}");
        assert_eq!(
            check(&lock).external,
            vec![external(
                "bar",
                "registry+https://github.com/rust-lang/crates.io-index"
            )]
        );
    }

    #[test]
    fn source_without_name_is_still_reported() {
        let lock = "[[package]]\nsource = \"registry+https://example.com/index\"\n";
        assert_eq!(
            check(lock).external,
            vec![external(
                "<ohne Namen>",
                "registry+https://example.com/index"
            )]
        );
    }

    #[test]
    fn empty_lock_has_no_entries() {
        assert_eq!(check("version = 4\n").entries, 0);
    }

    #[test]
    fn this_workspace_has_no_external_dependencies() {
        let report = check(include_str!("../../../Cargo.lock"));
        assert!(report.entries > 0);
        assert_eq!(report.external, Vec::new());
    }
}
