/// Allgemeine Kategorie eines Codepunkts (General_Category, UAX #44).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum GeneralCategory {
    /// `Cc`
    Control,
    /// `Cf`
    Format,
    /// `Cn`
    Unassigned,
    /// `Co`
    PrivateUse,
    /// `Cs`
    Surrogate,
    /// `Ll`
    LowercaseLetter,
    /// `Lm`
    ModifierLetter,
    /// `Lo`
    OtherLetter,
    /// `Lt`
    TitlecaseLetter,
    /// `Lu`
    UppercaseLetter,
    /// `Mc`
    SpacingMark,
    /// `Me`
    EnclosingMark,
    /// `Mn`
    NonspacingMark,
    /// `Nd`
    DecimalNumber,
    /// `Nl`
    LetterNumber,
    /// `No`
    OtherNumber,
    /// `Pc`
    ConnectorPunctuation,
    /// `Pd`
    DashPunctuation,
    /// `Pe`
    ClosePunctuation,
    /// `Pf`
    FinalPunctuation,
    /// `Pi`
    InitialPunctuation,
    /// `Po`
    OtherPunctuation,
    /// `Ps`
    OpenPunctuation,
    /// `Sc`
    CurrencySymbol,
    /// `Sk`
    ModifierSymbol,
    /// `Sm`
    MathSymbol,
    /// `So`
    OtherSymbol,
    /// `Zl`
    LineSeparator,
    /// `Zp`
    ParagraphSeparator,
    /// `Zs`
    SpaceSeparator,
}

